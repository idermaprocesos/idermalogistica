    public static int IndiceDe(IReadOnlyList<IconoAreaOpcion> opciones, string? glifo)
    {
        if (string.IsNullOrWhiteSpace(glifo))
        {
            return -1;
        }

        for (var i = 0; i < opciones.Count; i++)
        {
            if (GlifosWinUi.Mismo(opciones[i].Glifo, glifo))
            {
                return i;
            }
        }

        return -1;
    }
